from __future__ import annotations

import pytest

from arabic_bib import split_joined, title_key

KEYS = [
    ("كتاب الأمّ (ط. دار المعرفة) - الشافعي", "الام"),
    ("كتاب سيبويه", "سيبويه"),
    ("كتاب", "كتاب"),
    ("الرسالة ت أحمد شاكر", "الرساله"),
    ("مجموع الفتاوى ط مجمع الملك فهد", "مجموع الفتاوي"),
    ("القُرْآنُ الكَرِيمُ", "القران الكريم"),
    ("إحياء علوم الدين [نسخة الأزهر]", "احيا علوم الدين"),
    ("المغني - ابن قدامة - ت التركي", "المغني"),
    ("تفسير الطبري = جامع البيان", "تفسير الطبري جامع البيان"),
    ("سنن أبي داود", "سنن ابي داود"),
    ("الكامل في التاريخ: ابن الأثير", "الكامل في التاريخ ابن الاثير"),
    ("", ""),
]


@pytest.mark.parametrize("title, key", KEYS)
def test_title_key(title: str, key: str) -> None:
    assert title_key(title) == key


def test_split_joined() -> None:
    assert split_joined("جمع الجوامع ويليه همع الهوامع ومعه الكوكب الساطع") == [
        ("", "جمع الجوامع"), ("ويليه", "همع الهوامع"), ("ومعه", "الكوكب الساطع")]
    assert split_joined("الجامع لأحكام القرآن = تفسير القرطبي") == [("", "الجامع لأحكام القرآن"), ("=", "تفسير القرطبي")]
    assert split_joined("الأم") == [("", "الأم")]
